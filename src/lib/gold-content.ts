function generateDescription(venue: Venue, _label: string, _venueIndex = 0): string {
  const nm = venue.name;
  const hook = venue.card_hook || '';
  const nick = venue.nickname;
  const stn = venue.station || '';
  const hrs = venue.hours || '';
  const tag0 = (venue.tags && venue.tags[0]) || '';
  const tag1 = (venue.tags && venue.tags[1]) || '';
  const addr = venue.address || '';
  const kw = venue.keywords || [];
  const seoExtra = (venue as any).seo_extra || '';
  const h = hash(venue.slug + ':desc:v3');
  const pattern = h % 10;

  // 10가지 패턴으로 유사도 극단 분산 (같은 지역도 서로 다르게)
  const district = venue.district || '';
  const region = venue.region || '';
  // 이름의 고유 부분 추출 (마지막 단어 or 상호명)
  const nameParts = nm.split(' ');
  const shortName = nameParts.length > 1 ? nameParts[nameParts.length - 1] : nm;
  let desc: string;
  if (pattern === 0) {
    desc = nm + '. ' + hook;
  } else if (pattern === 1) {
    desc = hook + '. ' + nm;
  } else if (pattern === 2) {
    desc = (seoExtra || hook) + ' — ' + nm;
  } else if (pattern === 3) {
    desc = (stn ? stn + ' 근처 ' : '') + nm + '. ' + (seoExtra || hook);
  } else if (pattern === 4) {
    desc = nm + (hrs ? '(' + hrs + ')' : '') + '. ' + hook;
  } else if (pattern === 5) {
    desc = shortName + ', ' + hook + '. ' + nm;
  } else if (pattern === 6) {
    desc = hook + ' — ' + district + ' ' + shortName + '. ' + nm;
  } else if (pattern === 7) {
    desc = (seoExtra || shortName) + '. ' + nm + ', ' + hook;
  } else if (pattern === 8) {
    desc = nm + ' — ' + (seoExtra || hook) + '. ' + (stn || district);
  } else {
    desc = hook + '. ' + (stn ? stn + '에서 가까운 ' : '') + nm;
  }

  const extras: string[] = [];
  if (seoExtra && !desc.includes(seoExtra)) extras.push(seoExtra);
  if (stn && !desc.includes(stn)) extras.push(stn);
  if (hrs && !desc.includes(hrs)) extras.push(hrs);
  if (tag0 && !desc.includes(tag0)) extras.push(tag0);
  if (tag1 && !desc.includes(tag1)) extras.push(tag1);
  if (kw[1] && !desc.includes(kw[1])) extras.push(kw[1]);
  if (kw[2] && !desc.includes(kw[2])) extras.push(kw[2]);
  if (addr && addr.length < 40 && !desc.includes(addr)) extras.push(addr);
  if (nick && !desc.includes(nick)) extras.push(nick + ' 문의');

  for (const e of extras) {
    if ((desc + '. ' + e).length > 150) break;
    desc += '. ' + e;
  }

  desc = desc.replace(/\.\s*\./g, '.').replace(/\s{2,}/g, ' ').replace(/—\s*—/g, '—').trim();
  if (!desc.endsWith('.')) desc += '.';
  if (desc.length > 150) desc = desc.slice(0, 147) + '...';
  return desc;
}

/* ═══════════════════════════════════════
   메인 콘텐츠 생성
   ═══════════════════════════════════════ */
export function generateGoldContent(venue: Venue, venueIndex = 0) {
  const tagline = getTagline(venue, venueIndex);
  const label = catLabel[venue.cat_slug] || venue.category;

  const narrative = generateNarrative(venue, label);
  const faq = generateFaq(venue, label);
  const tips = pick(firstTimerTipPool, venue.slug, 6, 20);
  const description = generateDescription(venue, label, venueIndex);
  const timeSlots = generateTimeSlots(venue);
  const guide = generateGuide(venue);

  // 제목: 풀네임 + (region·label 중 name에 없는 것만 추가) + 단어 중복 제거
  const namePart = venue.name;
  const extras: string[] = [];
  if (venue.region && !namePart.includes(venue.region)) extras.push(venue.region);
  if (label && !namePart.includes(label)) extras.push(label);
  const rawTitle = [namePart, ...extras].join(' ');
  // 단어 단위 중복 제거 (2글자 이상 단어 기준, 첫 등장만 유지)
  const titleWords = rawTitle.split(/\s+/);
  const seen = new Set<string>();
  const deduped = titleWords.filter(w => {
    if (w.length < 2) return true;
    if (seen.has(w)) return false;
    seen.add(w);
    return true;
  });
  const nameWithExtras = deduped.join(' ');
  // "가게이름 — 후킹제목 | 놀쿨" 형식 (tagline에서 이름 중복단어 제거)
  let hookShort = tagline.length > 30 ? tagline.slice(0, 28) + '…' : tagline;
  // nameWithExtras에 이미 있는 2자+ 단어를 tagline에서 제거
  const nameWords = new Set(nameWithExtras.split(/\s+/).filter(w => w.length >= 2));
  hookShort = hookShort.split(/\s+/).filter(w => w.length < 2 || !nameWords.has(w)).join(' ').replace(/^[,\s·]+/, '').trim();
  const pageTitle = `${nameWithExtras} — ${hookShort}`;

  return {
    title: pageTitle,
    description,
    tagline,
    narrative,
    ogImage: `${SITE_URL}/og/${venue.cat_slug}-${venue.slug}.png`,
    guide,
    tips,
    faq,
    timeSlots,
  };
}

